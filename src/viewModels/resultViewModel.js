/**
 * The result screen's field bag, written once.
 *
 * GameRuntime.jsx used to assemble this bag inline, as two object literals on
 * two lines of 1,448 and 589 characters. The line budget counted them as two
 * lines, so every field a branch added made the runtime no longer in lines and
 * a little harder to read, and two branches adding a field to the same line
 * always conflicted.
 *
 * So the bag is assembled here, in three parts. Constants and the copy helpers
 * are imported once instead of being passed through the runtime; what the report
 * hook (`useResultReport`) derived arrives as its return value, unpacked here;
 * and only what the runtime alone knows -- its state, its handlers and the few
 * readouts it derives itself -- is passed by name.
 *
 * scripts/check-view-contracts.mjs reads the `createResultView` call below, so it
 * stays one object literal with every key written out: no spreads.
 */
