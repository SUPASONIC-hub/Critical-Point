-- 참가자 게시판: a report button on every post, and the table it writes to.
--
-- Why now. The board is the one place a player's words are published under a
-- name (20260923010000), and the store launch reads it as user-generated
-- content: Apple's guideline 1.2 and Google Play's UGC policy both ask for a
-- way to report objectionable content from inside the app, and a way for the
-- operator to act on it. Acting on it exists (`moderate_board_post`, service
-- role only, 20260928010000). Reporting did not.
--
-- What a report is: a post id, one of four reasons, and the board writer id
-- (`getBoardWriterId`, the board's own id, never the telemetry session's) --
-- nothing typed, so a report cannot carry the abuse it is about, and nothing
-- here is readable by anon. The writer key is `request_client_key()`
-- (20260929000000): a keyed hash, one key per IPv6 /64, never the address.
--
-- The defences, cheapest first, the board's own pattern:
--   1. Shape. The reason is one of 'spam', 'abuse', 'privacy', 'other'; the
--      session id is 8-128 characters, the event id 1-128.
--   2. A post that is there. Only a post anon can read (not hidden) can be
--      reported; anything else is refused by name, before the foreign key.
--   3. Once. The same writer reporting the same post again is accepted and
--      dropped, the way a retried post is: the client sees success and the
--      count of distinct writers is not inflated by pressing twice.
--   4. Pace. Ten reports an hour from one device on an address, thirty from an
--      address, in `telemetry_rate_limits` under a `board-report:` key, so a
--      reporting spree cannot spend the board's posting budget or the
--      other way round. Refused as PT429, like every refusal time cures.
--   5. Replay. `event_id` is unique, so a double press that sends twice writes
--      once (the client counts the 409 as delivered).
--
-- Nothing is hidden automatically. A report count that hides a post is a
-- button for hiding anyone's post from three addresses; a person reads the
-- queue and decides (the read is below).
--
-- Retention: a report goes with its post (`on delete cascade`), and
-- `purge_old_telemetry` deletes posts at 180 days, so no report outlives the
-- board's own retention and the purge function's row type is unchanged.
--
-- The operator's read, as service_role in the SQL editor (no admin screen yet):
--   select r.post_id, p.nickname, p.body, p.hidden,
--          count(*) as reports, count(distinct r.actor_key) as writers,
--          array_agg(distinct r.reason) as reasons, max(r.created_at) as last_report
--     from public.board_reports r join public.board_posts p on p.id = r.post_id
--    group by r.post_id, p.nickname, p.body, p.hidden
--    order by writers desc, last_report desc;
-- then `select public.moderate_board_post(<post_id>);` to hide one.

create table if not exists public.board_reports (
  id bigint generated by default as identity primary key,
  event_id text,
  post_id bigint not null references public.board_posts (id) on delete cascade,
  session_id text not null,
  reason text not null,
  actor_key text,
  created_at timestamptz not null default now(),
  constraint board_reports_event_id_key unique (event_id),
  constraint board_reports_reason_check check (reason in ('spam', 'abuse', 'privacy', 'other'))
);

create index if not exists board_reports_post_idx on public.board_reports (post_id, created_at desc);
create index if not exists board_reports_actor_idx on public.board_reports (actor_key, post_id);

alter table public.board_reports enable row level security;

-- Write-only for anon: four columns in, nothing out. The operator reads the
-- table as service_role.
revoke all on table public.board_reports from public, anon, authenticated;
grant all on table public.board_reports to service_role;

drop policy if exists "public can report board posts" on public.board_reports;
create policy "public can report board posts" on public.board_reports
for insert to anon
with check (
  length(session_id) between 8 and 128
  and reason in ('spam', 'abuse', 'privacy', 'other')
);

grant insert (event_id, post_id, session_id, reason) on public.board_reports to anon;

create or replace function public.validate_board_report_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_client text := public.request_client_key();
  v_writer text;
begin
  if new.session_id is null or length(new.session_id) not between 8 and 128 then
    raise exception 'invalid board report session id';
  end if;
  if new.event_id is not null and length(new.event_id) not between 1 and 128 then
    raise exception 'invalid board report event id';
  end if;
  if new.reason is null or new.reason not in ('spam', 'abuse', 'privacy', 'other') then
    raise exception 'invalid board report reason';
  end if;
  if new.post_id is null or not exists (
    select 1 from public.board_posts p where p.id = new.post_id and not p.hidden
  ) then
    raise exception 'board report names no visible post';
  end if;

  v_writer := 'board-report:' || coalesce(v_client, 'session:' || new.session_id);
  new.actor_key := left(v_writer, 200);
  new.created_at := now();

  perform pg_advisory_xact_lock(hashtext(new.actor_key));

  -- Once per writer and post: a second press is accepted and dropped.
  if exists (
    select 1 from public.board_reports r
    where r.actor_key = new.actor_key
      and r.post_id = new.post_id
  ) then
    return null;
  end if;

  if not public.bump_rate_limit(new.actor_key || '|' || new.session_id, interval '1 hour', 10)
    or not public.bump_rate_limit(new.actor_key, interval '1 hour', 30) then
    raise exception using errcode = 'PT429', message = 'board report rate limit exceeded';
  end if;

  return new;
end;
$$;

revoke all on function public.validate_board_report_insert() from public, anon, authenticated;
grant execute on function public.validate_board_report_insert() to service_role;

drop trigger if exists validate_board_reports_insert on public.board_reports;
create trigger validate_board_reports_insert
before insert on public.board_reports
for each row execute function public.validate_board_report_insert();

notify pgrst, 'reload schema';
